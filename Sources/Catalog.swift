enum Catalog {
    static func airline(for callsign: String) -> String? {
        let trimmed = callsign.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()
        guard trimmed.count >= 4 else { return nil }
        let prefix = String(trimmed.prefix(3))
        guard trimmed.dropFirst(3).contains(where: { $0.isNumber }) else { return nil }
        return airlines[prefix]
    }

    static func aircraftName(for code: String) -> String? {
        types[code.uppercased()]
    }

